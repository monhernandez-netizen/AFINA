self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c =>
    Promise.all(ARCHIVOS.map(u => c.add(u).catch(() => null)))
  ).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Tipografías de Google: se guardan la primera vez que hay internet
  if (url.hostname.endsWith('googleapis.com') || url.hostname.endsWith('gstatic.com')) {
    e.respondWith(caches.open(VERSION).then(c => c.match(req).then(hit => {
      const red = fetch(req).then(r => { c.put(req, r.clone()); return r; }).catch(() => hit);
      return hit || red;
    })));
    return;
  }
  if (url.origin !== location.origin) return;
  // Resto: primero lo guardado; si no está, internet
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(r => {
    const copia = r.clone(); caches.open(VERSION).then(c => c.put(req, copia)); return r;
  })));
});
